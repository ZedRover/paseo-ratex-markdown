import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { brotliCompressSync, constants } from "node:zlib";

// The Paseo server bundle is evaluated from a string: it has no plugin directory to read
// files from at runtime. The RaTeX WASM binary and the KaTeX fonts therefore travel inside
// the bundle as Brotli-compressed base64, generated from the pinned ratex-wasm package.

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const packageDir = path.join(root, "node_modules", "ratex-wasm");
const outDir = path.join(root, "server", "vendor");

// Every face RaTeX lays out with (ratex-types FontId), as shipped by ratex-wasm/fonts.
const FONT_IDS = [
  "AMS-Regular", "Caligraphic-Bold", "Caligraphic-Regular", "Fraktur-Bold", "Fraktur-Regular",
  "Main-Bold", "Main-BoldItalic", "Main-Italic", "Main-Regular", "Math-BoldItalic", "Math-Italic",
  "SansSerif-Bold", "SansSerif-Italic", "SansSerif-Regular", "Script-Regular", "Size1-Regular",
  "Size2-Regular", "Size3-Regular", "Size4-Regular", "Typewriter-Regular",
];

const manifest = JSON.parse(await readFile(path.join(root, "package.json"), "utf8"));
const installed = JSON.parse(await readFile(path.join(packageDir, "package.json"), "utf8"));
const pinned = manifest.dependencies["ratex-wasm"];
if (installed.version !== pinned) {
  throw new Error(`ratex-wasm ${installed.version} is installed, but package.json pins ${pinned}. Run npm ci.`);
}

function encode(bytes) {
  const compressed = brotliCompressSync(bytes, {
    params: {
      [constants.BROTLI_PARAM_QUALITY]: constants.BROTLI_MAX_QUALITY,
      [constants.BROTLI_PARAM_SIZE_HINT]: bytes.length,
    },
  });
  return {
    base64: compressed.toString("base64"),
    sha256: createHash("sha256").update(bytes).digest("hex"),
    size: bytes.length,
  };
}

const header = (source) =>
  `// Generated by scripts/embed-assets.mjs from ratex-wasm@${installed.version}/${source}. Do not edit.\n`;

await mkdir(outDir, { recursive: true });

const wasm = encode(await readFile(path.join(packageDir, "pkg", "ratex_wasm_bg.wasm")));
await writeFile(
  path.join(outDir, "ratex-wasm-bytes.ts"),
  header("pkg/ratex_wasm_bg.wasm") +
    `// ${wasm.size} bytes, sha256 ${wasm.sha256}; Brotli-compressed, then base64.\n` +
    `export const RATEX_WASM_BROTLI_BASE64 = "${wasm.base64}";\n`,
);

const fonts = [];
for (const id of FONT_IDS) {
  const font = encode(await readFile(path.join(packageDir, "fonts", `KaTeX_${id}.ttf`)));
  fonts.push({ id, ...font });
}
await writeFile(
  path.join(outDir, "katex-fonts.ts"),
  header("fonts/KaTeX_*.ttf") +
    "// KaTeX fonts: SIL Open Font License 1.1, see the LICENSE file in ratex-wasm.\n" +
    "// Brotli-compressed TrueType files, then base64, keyed by RaTeX font ID.\n" +
    fonts.map(({ id, size, sha256 }) => `// ${id}: ${size} bytes, sha256 ${sha256}\n`).join("") +
    "export const KATEX_FONTS_BROTLI_BASE64: Readonly<Record<string, string>> = {\n" +
    fonts.map(({ id, base64 }) => `  "${id}": "${base64}",\n`).join("") +
    "};\n",
);

const fontChars = fonts.reduce((sum, font) => sum + font.base64.length, 0);
console.log(
  `Embedded ratex-wasm@${installed.version}: WASM ${wasm.size} bytes as ${wasm.base64.length} characters, ` +
    `${fonts.length} fonts as ${fontChars} characters.`,
);
